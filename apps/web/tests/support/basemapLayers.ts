/** The layers as MapLibre lists them: a symbol with text has a `text-field`. */
export const asStyleLayers = (layers: readonly Layer[]) =>
  layers.map(([id, type, text]) => ({
    id,
    type,
    layout: text === undefined ? {} : { "text-field": ["get", "name"] },
  }));
